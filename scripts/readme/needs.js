// Writes the "What do you want to do?" section of README.md: for each need
// in scripts/lib/data.js, every listed system that meets it, with what it
// does and what it leaves you to rule on, copied from its own table row,
// a "How they differ" table built from scripts/lib/compare.js, and the close
// alternatives grouped under each featured system in scripts/lib/clusters.js.
// It also writes those alternatives under each category table.
// The section lives between two markers and is rebuilt on every run, so it
// cannot fall out of step with the tables. Run everything with:
//   node scripts/build.js
const fs = require('fs');
const path = require('path');
const { ROOT, readme, readRows, words } = require('../lib/readme');
const { NEEDS, TAGS, CATS, CHOOSER_URL } = require('../lib/data');
const { CHECKED, matrix, check } = require('../lib/compare');
const { checkClusters, clusterOf, alternatives } = require('../lib/clusters');

const START = '<!-- needs:start -->';
const END = '<!-- needs:end -->';
const NOTE = '<!-- Generated by node scripts/build.js from the category tables below, scripts/lib/data.js, scripts/lib/compare.js and scripts/lib/clusters.js. Edit those, not this section. -->';

// ---- agree with the README tables before writing anything ----
const rows = readRows();
const errors = [];
for (const r of rows) {
  if (!TAGS[r.name] || !TAGS[r.name].length) errors.push('README lists "' + r.name + '" but scripts/lib/data.js puts it under no need. Add it to TAGS.');
}
for (const [name, needs] of Object.entries(TAGS)) {
  if (!rows.some((r) => r.name === name)) errors.push('scripts/lib/data.js has "' + name + '" but the README tables do not. Remove it from TAGS.');
  for (const n of needs) if (!NEEDS[n]) errors.push('"' + name + '" is put under "' + n + '", which is not a need in NEEDS.');
}
for (const key of Object.keys(NEEDS)) {
  if (!rows.some((r) => (TAGS[r.name] || []).includes(key))) errors.push('No listed system meets the need "' + key + '". Give it a system or remove it.');
}
// Each panel lists its systems by category rank, then in README order.
const membersOf = (key) => rows
  .filter((r) => (TAGS[r.name] || []).includes(key))
  .sort((a, b) => CATS[a.cat].rank - CATS[b.cat].rank || rows.indexOf(a) - rows.indexOf(b));
errors.push(...checkClusters(rows, fs.readFileSync(path.join(ROOT, 'METHOD.md'), 'utf8')));
for (const cat of Object.keys(CATS)) {
  const m = readme().match(new RegExp('^\\| \\[' + cat + '\\]\\(#[a-z-]+\\) \\|.*\\| (\\d+) \\|\\s*$', 'm'));
  const n = rows.filter((r) => r.cat === cat).length;
  if (!m) errors.push('The "At a glance" table has no row for ' + cat + '.');
  else if (+m[1] !== n) errors.push('The "At a glance" table gives ' + cat + ' ' + m[1] + ' entries; its table has ' + n + '.');
}
if (!errors.length) {
  const byNeed = {};
  for (const key of Object.keys(NEEDS)) byNeed[key] = membersOf(key);
  errors.push(...check(byNeed));
}
if (errors.length) {
  console.error('Refusing to write the README needs section:\n  ' + errors.join('\n  '));
  process.exit(1);
}

// ---- build the section ----
const cap = (s) => s[0].toUpperCase() + s.slice(1);
// "Close to X", then one line per member: what it does differently.
function closeList(c) {
  return ['**Close to ' + c.featured + '** &middot; *' + c.title + '*', '']
    .concat(c.members.map((m) => '- [' + m.name + '](' + m.url + ')' + (m.was ? ' *(own row until ' + m.was + ')*' : '') + ': ' + m.line + ' ([source](' + m.src.url + '))'))
    .concat(['']);
}
const anchor = (cat) => '#' + cat.toLowerCase().replace(/\s+/g, '-');
const LEGEND = 'In *How they differ*, ✓ and ✗ rest on the vendor’s own pages or on the system’s own row further down, and **†** marks evidence found only in page source, a script bundle or a repository’s code. In the evaluation row, ✓ names the published study. *Not documented* means nothing we found on its public pages says either way. Checked ' + CHECKED + '.';
const out = [START, NOTE, '', LEGEND];
for (const [key, need] of Object.entries(NEEDS)) {
  const members = membersOf(key);
  const cats = [...new Set(members.map((m) => m.cat))];
  const n = members.length;
  const clusters = members.map((m) => clusterOf(m.name)).filter(Boolean);
  const alts = clusters.reduce((k, c) => k + c.members.length, 0);
  let lead;
  if (cats.length > 1) lead = cap(words(n)) + ' systems across ' + words(cats.length) + ' categories, so they leave you different things to rule on.';
  else if (n === 1) lead = 'One system, in ' + cats[0] + '.';
  else if (n === 2) lead = 'Both in ' + cats[0] + ', so they leave you the same kind of thing to rule on.';
  else lead = cap(words(n)) + ' systems, all in ' + cats[0] + ', so they leave you the same kind of thing to rule on.';
  // A collapsed panel per need: the reader clicks the need and its systems
  // open. GitHub renders details/summary natively, with no script. The blank
  // line after the summary is what lets the markdown table inside render.
  out.push('', '<details>', '<summary><b>' + need.label + '</b> &middot; ' + n + (n === 1 ? ' system' : ' systems') + (alts ? ', ' + alts + (alts === 1 ? ' close alternative' : ' close alternatives') : '') + '</summary>', '');
  out.push(lead + ' [' + (n === 1 ? 'See its card' : 'Compare them side by side') + '](' + CHOOSER_URL + '#job=' + key + ').', '');
  out.push('| System | What it does | What you still rule on | Category |', '| --- | --- | --- | --- |');
  for (const m of members) {
    out.push('| [' + m.name + '](' + m.url + ') | ' + m.cells[1] + ' | ' + m.cells[2] + ' | [' + m.cat + '](' + anchor(m.cat) + ') |');
  }
  // Close alternatives, under the featured system they resemble.
  for (const c of clusters) out.push('', ...closeList(c).slice(0, -1));
  // Where the systems in the panel differ, from scripts/lib/compare.js.
  const mx = matrix(key, members);
  if (mx.length) {
    out.push('', '**How they differ**', '');
    out.push('| | ' + members.map((m) => m.name).join(' | ') + ' |', '| --- |' + members.map(() => ' :---: |').join(''));
    for (const r of mx) out.push('| ' + r.label + ' | ' + r.cells.map((c) => (c.cell.v === 'nd' ? '*' + c.text + '*' : c.text)).join(' | ') + ' |');
  }
  out.push('', '</details>');
}
out.push('', END);
const block = out.join('\n');

// ---- put it between the markers ----
const text = readme();
const i = text.indexOf(START), j = text.indexOf(END);
if (i < 0 || j < 0 || j < i) {
  console.error('README.md needs the markers ' + START + ' and ' + END + ' around the needs section.');
  process.exit(1);
}
let next = text.slice(0, i) + block + text.slice(j + END.length);

// ---- close alternatives under each category table ----
for (const cat of Object.keys(CATS)) {
  const a = '<!-- close:start ' + cat + ' -->', b = '<!-- close:end ' + cat + ' -->';
  const p = next.indexOf(a), q = next.indexOf(b);
  if (p < 0 || q < p) { console.error('README.md needs the markers ' + a + ' and ' + b + ' under the ' + cat + ' table.'); process.exit(1); }
  const cs = rows.filter((r) => r.cat === cat).map((r) => clusterOf(r.name)).filter(Boolean);
  const body = cs.length ? ['', '**Close alternatives.** Grouped by the system in the table above that each most resembles, with one documented difference and its source.', ''].concat(...cs.map(closeList), ['']) : ['', ''];
  next = next.slice(0, p + a.length) + body.join('\n') + next.slice(q);
}

// ---- the one count the README prose states about the list as a whole ----
const want = cap(words(rows.length)) + ' systems a researcher can use today';
if (!next.includes(want)) {
  console.error('README is out of step with its tables. Expected to find: "' + want + '"');
  process.exit(1);
}
const altCount = alternatives();
const wantAlts = words(altCount) + (altCount === 1 ? ' close alternative' : ' close alternatives');
if (altCount && !new RegExp('(^|[^a-z-])' + wantAlts + '\\b', 'i').test(next)) {
  console.error('README is out of step with scripts/lib/clusters.js. Expected to find: "' + wantAlts + '"');
  process.exit(1);
}

if (next !== text) fs.writeFileSync(path.join(ROOT, 'README.md'), next);
const per = Object.keys(NEEDS).map((k) => k + ' ' + rows.filter((r) => TAGS[r.name].includes(k)).length).join(', ');
console.log('readme: needs section ' + (next !== text ? 'rewritten' : 'unchanged') + ' (' + per + ')');
